        // Load users data into table
    public void loadDataSet() {
        try {
            ResultSet rs = userDAO.getQueryResult();
            DefaultTableModel model = new DefaultTableModel();
            model.setColumnIdentifiers(new String[]{"USERNAME", "FULL NAME", "LOCATION", "CONTACT", "USER TYPE"});
            
            if (rs != null) {
                while (rs.next()) {
                    model.addRow(new Object[]{
                        rs.getString("username"),
                        rs.getString("fullname"),
                        rs.getString("location"),
                        rs.getString("phone"),
                        rs.getString("usertype")
                    });
                }
                rs.close();
            }
            userTable.setModel(model);
            
            if (model.getRowCount() > 0) {
                customizeTable();
            }
        } catch (SQLException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error loading users: " + ex.getMessage());
            userTable.setModel(new DefaultTableModel());
        }
    }
    
    // Search users
    private void searchUsers() {
        String searchText = searchField.getText().trim();
        
        if (searchText.isEmpty()) {
            loadDataSet();
        } else {
            try {
                ResultSet rs = userDAO.searchUsers(searchText);
                DefaultTableModel model = new DefaultTableModel();
                model.setColumnIdentifiers(new String[]{"USERNAME", "FULL NAME", "LOCATION", "CONTACT", "USER TYPE"});
                
                if (rs != null) {
                    while (rs.next()) {
                        model.addRow(new Object[]{
                            rs.getString("username"),
                            rs.getString("fullname"),
                            rs.getString("location"),
                            rs.getString("phone"),
                            rs.getString("usertype")
                        });
                    }
                    rs.close();
                }
                userTable.setModel(model);
                
                if (model.getRowCount() > 0) {
                    customizeTable();
                }
            } catch (SQLException ex) {
                ex.printStackTrace();
            }
        }
    }
    
