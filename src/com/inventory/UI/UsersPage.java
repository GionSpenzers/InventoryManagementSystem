    // Customize table appearance
    private void customizeTable() {
        try {
            if (userTable.getColumnCount() == 0) return;
            
            userTable.getColumnModel().getColumn(0).setPreferredWidth(100);  // Username
            userTable.getColumnModel().getColumn(1).setPreferredWidth(180);  // Full Name
            userTable.getColumnModel().getColumn(2).setPreferredWidth(120);  // Location
            userTable.getColumnModel().getColumn(3).setPreferredWidth(100);  // Contact
            userTable.getColumnModel().getColumn(4).setPreferredWidth(100);  // User Type
            
            userTable.setFont(new Font("Segoe UI", Font.PLAIN, 12));
            userTable.setRowHeight(25);
            
            JTableHeader header = userTable.getTableHeader();
            header.setFont(new Font("Segoe UI", Font.BOLD, 12));
            header.setBackground(new Color(240, 240, 240));
        } catch (Exception e) {
            e.printStackTrace();
        }
    }
    
    // Add new user
    private void addUser() {
        if (nameText.getText().trim().isEmpty() ||
            locationText.getText().trim().isEmpty() ||
            contactText.getText().trim().isEmpty() ||
            usernameText.getText().trim().isEmpty() ||
            passwordText.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please fill all required fields.");
            return;
        }
        
        UserDTO userDTO = new UserDTO();
        String userType = ((String) userTypeComboBox.getSelectedItem()).toUpperCase();
        userDTO.setFullName(nameText.getText().trim());
        userDTO.setLocation(locationText.getText().trim());
        userDTO.setPhone(contactText.getText().trim());
        userDTO.setUsername(usernameText.getText().trim());
        userDTO.setPassword(passwordText.getText().trim());
        userDTO.setUserType(userType);
        
        userDAO.addUserDAO(userDTO, userType);
        loadDataSet();
        clearForm();
        JOptionPane.showMessageDialog(null, "User added successfully!");
    }
    
    // Update existing user
    private void updateUser() {
        if (originalUsername == null) {
            JOptionPane.showMessageDialog(null, "No user selected for update.");
            return;
        }
        
        if (nameText.getText().trim().isEmpty() ||
            locationText.getText().trim().isEmpty() ||
            contactText.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please fill all required fields.");
            return;
        }
        
        String newUsername = usernameText.getText().trim();
        String userType = ((String) userTypeComboBox.getSelectedItem()).toUpperCase();
        
        UserDTO userDTO = new UserDTO();
        userDTO.setFullName(nameText.getText().trim());
        userDTO.setLocation(locationText.getText().trim());
        userDTO.setPhone(contactText.getText().trim());
        userDTO.setUsername(newUsername);
        userDTO.setUserType(userType);
        
        // If password is provided, update it
        if (!passwordText.getText().trim().isEmpty()) {
            userDTO.setPassword(passwordText.getText().trim());
            userDAO.updateUserWithPassword(userDTO, originalUsername);
        } else {
            userDAO.updateUser(userDTO, originalUsername);
        }
        
        loadDataSet();
        clearForm();
        JOptionPane.showMessageDialog(null, "User updated successfully!");
    }
    
    // Delete user
    private void deleteUser() {
        int selectedRow = userTable.getSelectedRow();
        if (selectedRow < 0) {
            JOptionPane.showMessageDialog(null, "Please select a user to delete.");
            return;
        }
        
        String username = userTable.getValueAt(selectedRow, 0).toString();
        
        int confirm = JOptionPane.showConfirmDialog(null,
            "Are you sure you want to delete user: " + username + "?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION);
            
        if (confirm == JOptionPane.YES_OPTION) {
            userDAO.deleteUserDAO(username);
            loadDataSet();
            clearForm();
            JOptionPane.showMessageDialog(null, "User deleted successfully!");
        }
    }
    
    // Refresh data
    private void refreshData() {
        loadDataSet();
        clearForm();
        JOptionPane.showMessageDialog(null, "Data refreshed!");
    }
    
