    private void userTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_userTableMouseClicked
        int row = userTable.getSelectedRow();
        if (row >= 0) {
            originalUsername = userTable.getValueAt(row, 0).toString();
            usernameText.setText(originalUsername);
            usernameText.setEnabled(true);  // Allow editing
            nameText.setText(userTable.getValueAt(row, 1).toString());
            locationText.setText(userTable.getValueAt(row, 2).toString());
            contactText.setText(userTable.getValueAt(row, 3).toString());
            
            String userType = userTable.getValueAt(row, 4).toString();
            if (userType.equalsIgnoreCase("ADMINISTRATOR")) {
                userTypeComboBox.setSelectedIndex(0);
            } else {
                userTypeComboBox.setSelectedIndex(1);
            }
            
            passwordText.setText("");  // Clear password field for security
            
            isEditMode = true;
            updateButton.setEnabled(true);
            addButton.setEnabled(true);
        }      
    }//GEN-LAST:event_userTableMouseClicked

