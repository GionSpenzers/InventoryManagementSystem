    // Load suppliers into combo box
    public void loadSuppliersToCombo() {
        try {
            ResultSet rs = supplierDAO.getSuppliersForCombo();
            suppCombo.removeAllItems();
            suppCombo.addItem("-- Select Supplier --");
            while (rs.next()) {
                suppCombo.addItem(rs.getString("fullname"));
            }
            rs.close();
        } catch (SQLException e) {
            e.printStackTrace();
        }
    }
    
    // Load products data into table
    public void loadProductsData() {
        try {
            ResultSet rs = productDAO.getQueryResult();
            DefaultTableModel model = new DefaultTableModel();
            model.setColumnIdentifiers(new String[]{"PRODUCT CODE", "PRODUCT NAME", "COST PRICE", "SELL PRICE", "BRAND"});
            
            if (rs != null) {
                while (rs.next()) {
                    model.addRow(new Object[]{
                        rs.getString("productcode"),
                        rs.getString("productname"),
                        String.format("%.2f", rs.getDouble("costprice")),
                        String.format("%.2f", rs.getDouble("sellprice")),
                        rs.getString("brand")
                    });
                }
                rs.close();
            }
            productsTable.setModel(model);
            
            if (model.getRowCount() > 0) {
                customizeTable();
            }
        } catch (SQLException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error loading products: " + ex.getMessage());
        }
    }
    
    // Search products
    private void searchProducts() {
        String searchText = searchField.getText().trim();
        
        if (searchText.isEmpty()) {
            loadProductsData();
        } else {
            try {
                ResultSet rs = productDAO.getProductSearch(searchText);
                DefaultTableModel model = new DefaultTableModel();
                model.setColumnIdentifiers(new String[]{"PRODUCT CODE", "PRODUCT NAME", "COST PRICE", "SELL PRICE", "BRAND"});
                
                if (rs != null) {
                    while (rs.next()) {
                        model.addRow(new Object[]{
                            rs.getString("productcode"),
                            rs.getString("productname"),
                            String.format("%.2f", rs.getDouble("costprice")),
                            String.format("%.2f", rs.getDouble("sellprice")),
                            rs.getString("brand")
                        });
                    }
                    rs.close();
                }
                productsTable.setModel(model);
                
                if (model.getRowCount() > 0) {
                    customizeTable();
                }
            } catch (SQLException ex) {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(null, "Error searching products: " + ex.getMessage());
            }
        }
    }
    
