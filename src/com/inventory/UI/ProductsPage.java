    // Update existing product
    private void updateProduct() {
            if (nameText.getText().trim().isEmpty() ||
            costText.getText().trim().isEmpty() ||
            sellText.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please fill all required fields.");
            return;
        }

        try {
            String newProductCode = codeText.getText().trim().toUpperCase();
            String oldProductCode = originalProductCode;

            ProductDTO productDTO = new ProductDTO();
            productDTO.setProdCode(newProductCode);
            productDTO.setProdName(nameText.getText().trim());
            productDTO.setCostPrice(Double.parseDouble(costText.getText().trim()));
            productDTO.setSellPrice(Double.parseDouble(sellText.getText().trim()));
            productDTO.setBrand(brandText.getText().trim());

            // If product code changed, update everything
            if (!newProductCode.equals(oldProductCode)) {
                productDAO.updateProductWithCodeChange(productDTO, oldProductCode);
            } else {
                productDAO.editProdDAO(productDTO);
            }

            loadProductsData();
            clearForm();
            JOptionPane.showMessageDialog(null, "Product updated successfully!");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Please enter valid numbers for price.");
        }
    }
    
    // Delete product
    private void deleteProduct() {
        int selectedRow = productsTable.getSelectedRow();
        if (selectedRow < 0) {
            JOptionPane.showMessageDialog(null, "Please select a product to delete.");
            return;
        }
        
        String productCode = productsTable.getValueAt(selectedRow, 0).toString();
        
        int confirm = JOptionPane.showConfirmDialog(null,
            "Are you sure you want to delete product: " + productCode + "?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION);
            
        if (confirm == JOptionPane.YES_OPTION) {
            productDAO.deleteProductDAO(productCode);
            loadProductsData();
            clearForm();
        }
    }
    
