    // Add new purchase transaction
    private void addPurchase() {
        if (suppCombo.getSelectedIndex() <= 0) {
            JOptionPane.showMessageDialog(null, "Please select a supplier.");
            return;
        }
        if (codeText.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please enter Product Code.");
            return;
        }
        if (quantityText.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please enter Quantity.");
            return;
        }
        if (costText.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Cost price not found for this product.");
            return;
        }
        
        try {
            // Get selected supplier code
            String selectedSupplier = suppCombo.getSelectedItem().toString();
            String supplierCode = selectedSupplier.substring(selectedSupplier.indexOf("(") + 1, selectedSupplier.indexOf(")"));
            
            ProductDTO productDTO = new ProductDTO();
            productDTO.setSuppCode(supplierCode);
            productDTO.setProdCode(codeText.getText().trim().toUpperCase());
            productDTO.setProdName(nameText.getText().trim());
            
            SimpleDateFormat dateFormat = new SimpleDateFormat("yyyy-MM-dd");
            String date = dateFormat.format(jDateChooser1.getDate());
            productDTO.setDate(date);
            
            int quantity = Integer.parseInt(quantityText.getText().trim());
            double costPrice = Double.parseDouble(costText.getText().trim());
            double totalCost = quantity * costPrice;
            
            productDTO.setQuantity(quantity);
            productDTO.setTotalCost(totalCost);
            productDTO.setCostPrice(costPrice);
            
            if (!sellText.getText().trim().isEmpty()) {
                productDTO.setSellPrice(Double.parseDouble(sellText.getText().trim()));
            }
            productDTO.setBrand(brandText.getText().trim());
            
            productDAO.addPurchaseDAO(productDTO);
            loadPurchaseData();
            clearForm();
            JOptionPane.showMessageDialog(null, "Purchase transaction completed successfully!");
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Please enter valid numbers for Quantity.");
        }
    }
    
