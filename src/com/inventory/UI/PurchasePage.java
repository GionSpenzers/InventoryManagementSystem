    // Delete purchase
    private void deletePurchase() {
        int selectedRow = purchaseTable.getSelectedRow();
        if (selectedRow < 0) {
            JOptionPane.showMessageDialog(null, "Please select a purchase record to delete.");
            return;
        }
        
        int purchaseID = (int) purchaseTable.getValueAt(selectedRow, 0);
        
        int confirm = JOptionPane.showConfirmDialog(null,
            "Are you sure you want to delete purchase record #" + purchaseID + "?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION);
            
        if (confirm == JOptionPane.YES_OPTION) {
            productDAO.deletePurchaseDAO(purchaseID);
            loadPurchaseData();
            clearForm();
            JOptionPane.showMessageDialog(null, "Purchase record deleted successfully!");
        }
    }
    
