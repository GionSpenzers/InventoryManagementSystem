    // Load product details automatically when product code is entered
    private void loadProductDetails() {
        String productCode = codeText.getText().trim();
        if (!productCode.isEmpty()) {
            try {
                ResultSet rs = productDAO.getProdFromCode(productCode);
                if (rs != null && rs.next()) {
                    nameText.setText(rs.getString("productname"));
                    costText.setText(String.format("%.2f", rs.getDouble("costprice")));
                    sellText.setText(String.format("%.2f", rs.getDouble("sellprice")));
                    brandText.setText(rs.getString("brand"));
                    
                    // Auto-calculate total cost if quantity is already entered
                    calculateTotalCost();
                    rs.close();
                } else {
                    // Clear fields if product not found
                    nameText.setText("");
                    costText.setText("");
                    sellText.setText("");
                    brandText.setText("");
                    JOptionPane.showMessageDialog(null, "Product not found. Please check the product code.");
                }
            } catch (SQLException e) {
                e.printStackTrace();
            }
        } else {
            // Clear fields if product code is empty
            nameText.setText("");
            costText.setText("");
            sellText.setText("");
            brandText.setText("");
        }
    }
    
    // Calculate and display total cost
    private void calculateTotalCost() {
        try {
            int quantity = 0;
            double costPrice = 0;
            
            if (!quantityText.getText().trim().isEmpty()) {
                quantity = Integer.parseInt(quantityText.getText().trim());
            }
            if (!costText.getText().trim().isEmpty()) {
                costPrice = Double.parseDouble(costText.getText().trim());
            }
            
            double totalCost = quantity * costPrice;
            // Display total cost in a label if you have one, or store for later use
            System.out.println("Total Cost: " + totalCost);
            
            // If you have a totalCostLabel, uncomment:
            // totalCostLabel.setText(String.format("Total Cost: %.2f", totalCost));
        } catch (NumberFormatException e) {
            // Ignore invalid input
        }
    }
    
    // Load purchase data into table
    public void loadPurchaseData() {
        try {
            ResultSet rs = productDAO.getPurchaseInfo();
            DefaultTableModel model = new DefaultTableModel();
            model.setColumnIdentifiers(new String[]{"PURCHASE ID", "PRODUCT CODE", "PRODUCT NAME", "QUANTITY", "TOTAL COST"});
            
            if (rs != null) {
                while (rs.next()) {
                    model.addRow(new Object[]{
                        rs.getInt("purchaseID"),
                        rs.getString("productcode"),
                        rs.getString("productname"),
                        rs.getInt("quantity"),
                        String.format("%.2f", rs.getDouble("totalcost"))
                    });
                }
                rs.close();
            }
            purchaseTable.setModel(model);
            
            if (model.getRowCount() > 0) {
                customizeTable();
            }
        } catch (SQLException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error loading purchase data: " + ex.getMessage());
        }
    }
    
    // Search purchase records
    private void searchPurchase() {
        String searchText = searchField.getText().trim();
        
        if (searchText.isEmpty()) {
            loadPurchaseData();
        } else {
            try {
                ResultSet rs = productDAO.getPurchaseSearch(searchText);
                DefaultTableModel model = new DefaultTableModel();
                model.setColumnIdentifiers(new String[]{"PURCHASE ID", "PRODUCT CODE", "PRODUCT NAME", "QUANTITY", "TOTAL COST"});
                
                if (rs != null) {
                    while (rs.next()) {
                        model.addRow(new Object[]{
                            rs.getInt("purchaseID"),
                            rs.getString("productcode"),
                            rs.getString("productname"),
                            rs.getInt("quantity"),
                            String.format("%.2f", rs.getDouble("totalcost"))
                        });
                    }
                    rs.close();
                }
                purchaseTable.setModel(model);
                
                if (model.getRowCount() > 0) {
                    customizeTable();
                }
            } catch (SQLException ex) {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(null, "Error searching purchase: " + ex.getMessage());
            }
        }
    }
    
