    // Helper method to load purchase details for editing
    private void loadPurchaseDetails(int purchaseID) {
        try {
            ResultSet rs = productDAO.getPurchaseById(purchaseID);
            if (rs != null && rs.next()) {
                // Set quantity
                quantityText.setText(String.valueOf(rs.getInt("quantity")));
                
                // Set date
                String dateStr = rs.getString("date");
                if (dateStr != null && !dateStr.isEmpty()) {
                    SimpleDateFormat dateFormat = new SimpleDateFormat("yyyy-MM-dd");
                    Date date = dateFormat.parse(dateStr);
                    jDateChooser1.setDate(date);
                }
                rs.close();
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }
    
    // Load suppliers into combo box
    private void loadSuppliersToCombo() {
        try {
            ResultSet rs = supplierDAO.getAllSuppliers();
            suppCombo.removeAllItems();
            suppCombo.addItem("-- Select Supplier --");
            while (rs.next()) {
                suppCombo.addItem(rs.getString("fullname") + " (" + rs.getString("suppliercode") + ")");
            }
            rs.close();
        } catch (SQLException e) {
            e.printStackTrace();
        }
    }
    
    

